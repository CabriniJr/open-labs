import { expect, test } from "@playwright/test";

test("normalize: each normal form measures the anomalies, and 3NF reaches the server", async ({ page }) => {
  const erros: string[] = [];
  page.on("pageerror", (e) => erros.push(String(e)));
  await page.goto("labs/normalize-a-spreadsheet/");
  await expect(page.getByTestId("normalize-showcase")).toBeVisible();

  await page.getByRole("tab", { name: /Simulation/ }).click();
  const sim = page.getByTestId("normalize-simulation");
  await sim.getByRole("button", { name: /Rename Telecentro Jardim Ângela/ }).click();
  await expect(sim.getByRole("status")).toContainText("4 cells must change together");

  await sim.getByRole("tab", { name: "1NF" }).click();
  await expect(sim).toContainText("7 of 12");
  await sim.getByRole("button", { name: /Delete the attempts at assessment 6/ }).click();
  await expect(sim.getByRole("status")).toContainText("Splunk Visual Handbook");

  await sim.getByRole("tab", { name: "3NF" }).click();
  await sim.getByRole("button", { name: "Open a telecentre with no learners" }).click();
  await expect(sim.getByRole("status")).toContainText("one row in T_TELECENTRO");
  await expect(sim).toContainText("Telecentro Novo Horizonte");
  await expect(sim).toContainText("GENERATED BY DEFAULT ON NULL AS IDENTITY");

  const overflow = await page.evaluate(() => document.documentElement.scrollWidth - document.documentElement.clientWidth);
  expect(overflow).toBeLessThanOrEqual(1);
  expect(erros).toEqual([]);
});
