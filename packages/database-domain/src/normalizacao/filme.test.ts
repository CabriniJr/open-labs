import { frameAt, type Film } from "@ovh/motion";
import { describe, expect, it } from "vitest";
import { CAPITULOS_DA_NORMALIZACAO, filmeDaNormalizacao, type DetalheDaNormalizacao } from "./filme.js";

const fim = (f: Film<DetalheDaNormalizacao>, id: string) => {
  const c = f.chapters.find((x) => x.id === id);
  if (c === undefined) throw new Error(id);
  return frameAt(f, c.end - 50);
};
const peca = (q: ReturnType<typeof fim>, id: string) => q.entities.find((e) => e.spec.id === id)?.state;

describe("o filme da normalização", () => {
  const f = filmeDaNormalizacao();

  it("tem as etapas na ordem", () => expect(f.chapters.map((c) => c.id)).toEqual([...CAPITULOS_DA_NORMALIZACAO]));

  it("a planilha mostra as anomalias medidas, não escritas", () => {
    const q = fim(f, "planilha");
    expect(q.detail?.linhas).toContainEqual(["rename Telecentro Jardim Ângela", "4 cells to change"]);
    expect(q.detail?.linhas).toContainEqual(["a telecentre with no learners yet", "nowhere to put it"]);
  });

  it("na 1FN, 5 alunos somem e a planilha fica vermelha", () => {
    const q = fim(f, "1fn");
    expect(q.detail?.linhas).toContainEqual(["learners the tables can hold", "7 of 12"]);
    expect(peca(q, "sheet")?.tone).toBe("live");
  });

  it("na 3FN as sete tabelas reais aparecem, ligadas pelas chaves estrangeiras", () => {
    const q = fim(f, "3fn");
    for (const t of ["T_TELECENTRO", "T_ALUNO", "T_TENTATIVA", "T_AVALIACAO", "T_LAB", "T_FASE", "T_HANDBOOK"]) expect(peca(q, t)?.opacity).toBe(1);
    expect(peca(q, "ALUNO_2FN")?.opacity).toBe(0);
    expect(peca(q, "fk3:T_ALUNO:id_telecentro")?.progress).toBe(1);
    expect(q.detail?.linhas).toContainEqual(["rename Telecentro Jardim Ângela", "1 cell to change"]);
  });

  it("no servidor, o POST da API recebe o id que a IDENTITY dá", () => {
    const q = fim(f, "servidor");
    expect(q.detail?.sql).toContain("GENERATED BY DEFAULT ON NULL AS IDENTITY (START WITH 13)");
    expect(q.detail?.linhas).toContainEqual(["POST /alunos", "1 row inserted. id_aluno = 13"]);
    expect(peca(q, "T_ALUNO")?.sublabel).toBe("13 rows · id 13 by IDENTITY");
  });
});
