/** Em que página do PDF está o título de cada seção (pulando capa e sumário). */
function paginasDasSecoes(arquivo) {
  const alvos = Object.fromEntries(SECOES.map(([id, n, t]) => [id, `${n} ${t}`]));
  const script = "import sys,json,pymupdf\nd=pymupdf.open(sys.argv[1]);a=json.loads(sys.stdin.buffer.read().decode('utf-8'));r={}\nfor i,p in enumerate(d):\n  if i<2: continue\n  t=' '.join(p.get_text().split())\n  for k,v in a.items():\n    if k not in r and v in t: r[k]=i+1\nprint(json.dumps(r))";
  const r = spawnSync("python", ["-c", script, arquivo], { input: JSON.stringify(alvos), encoding: "utf8" });
  if (r.status !== 0) return null;
  try {
    return JSON.parse(r.stdout);
  } catch {
    return null;
  }
}
