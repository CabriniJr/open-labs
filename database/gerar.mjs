/**
 * A chave primária de cada tabela é gerada pelo Oracle (IDENTITY): a API Java
 * faz POST sem mandar o id, e o banco devolve o próximo número. "BY DEFAULT ON
 * NULL" ainda aceita o id escrito à mão, que é como o 02-dml.sql insere os dados
 * de exemplo; por isso o contador começa logo depois do maior id desses dados.
 */
function proximoId(t) {
  const i = t.colunas.findIndex((c) => c.nome === t.pk);
  return Math.max(0, ...DADOS[t.nome].linhas.map((l) => Number(l[i]))) + 1;
}
const identidade = (t) => `GENERATED BY DEFAULT ON NULL AS IDENTITY (START WITH ${proximoId(t)})`;

// ------------------------------------------------------------------ 01-ddl.sql

function ddl() {
  const linhas = [
    "-- =====================================================================",
    "-- OpenLabs no Telecentro — Script DDL (Oracle)",
    "-- Global Solution 2026.2 · Database Design",
    "--",
    "-- Gerado por database/gerar.mjs a partir de packages/database-domain.",
    "-- Ordem de execução: 01-ddl.sql → 02-dml.sql → 03-dql.sql.",
    "-- =====================================================================",
    "",
    "-- Apaga as tabelas de uma execução anterior, para o script poder rodar de novo.",
    "-- Na primeira execução elas não existem, e o erro ORA-00942 é ignorado.",
    "BEGIN",
    ...[...TABELAS].reverse().map((t) => `  BEGIN EXECUTE IMMEDIATE 'DROP TABLE ${t.nome} CASCADE CONSTRAINTS'; EXCEPTION WHEN OTHERS THEN IF SQLCODE != -942 THEN RAISE; END IF; END;`),
    "END;",
    "/",
    "",
    "-- ---------------------------------------------------------------------",
    "-- 1. Tabelas (CREATE TABLE): colunas, tipos, obrigatoriedade e padrões",
    "--    A chave primária de cada tabela é gerada pelo Oracle (IDENTITY):",
    "--    quem insere (a API Java, por exemplo) pode omitir o id. O contador",
    "--    começa depois dos ids usados pelos dados de exemplo do 02-dml.sql.",
    "-- ---------------------------------------------------------------------",
  ];
  for (const t of TABELAS) {
    linhas.push("", `-- ${t.descricao}`, `CREATE TABLE ${t.nome} (`);
    const largura = Math.max(...t.colunas.map((c) => c.nome.length));
    t.colunas.forEach((c, i) => {
      const partes = [c.nome.padEnd(largura), c.tipo];
      if (c.nome === t.pk) partes.push(identidade(t));
      if (c.padrao) partes.push(`DEFAULT ${c.padrao}`);
      partes.push(c.nulo ? "NULL" : "NOT NULL");
      linhas.push(`  ${partes.join(" ")}${i < t.colunas.length - 1 ? "," : ""}`);
    });
    linhas.push(");");
  }
  linhas.push("", "-- ---------------------------------------------------------------------", "-- 2. Restrições (ALTER TABLE): chaves primárias, únicas e regras de valor", "-- ---------------------------------------------------------------------");
  for (const t of TABELAS) {
    const cs = constraints(t).filter((c) => c.tipo !== "FK");
    linhas.push("");
    for (const c of cs) linhas.push(`ALTER TABLE ${t.nome} ADD CONSTRAINT ${c.nome} ${c.sql};`);
  }
  linhas.push("", "-- ---------------------------------------------------------------------", "-- 3. Relacionamentos (ALTER TABLE): chaves estrangeiras", "-- ---------------------------------------------------------------------");
  for (const t of TABELAS) {
    const fks = constraints(t).filter((c) => c.tipo === "FK");
    if (fks.length === 0) continue;
    linhas.push("");
    t.fks.forEach((f, i) => linhas.push(`-- ${f.cardinalidade}`, `ALTER TABLE ${t.nome} ADD CONSTRAINT ${fks[i].nome} ${fks[i].sql};`));
  }
  const aspas = (s) => s.replaceAll("'", "''");
  linhas.push("", "-- ---------------------------------------------------------------------", "-- 4. Comentários: o dicionário de dados dentro do próprio banco", "--    (o Oracle Data Modeler os importa junto com as tabelas)", "-- ---------------------------------------------------------------------");
  for (const t of TABELAS) {
    linhas.push("", `COMMENT ON TABLE ${t.nome} IS '${aspas(t.descricao)}';`);
    for (const c of t.colunas) linhas.push(`COMMENT ON COLUMN ${t.nome}.${c.nome} IS '${aspas(c.descricao)}';`);
  }
  return linhas.join("\n") + "\n";
}

// ------------------------------------------------------------------ 02-dml.sql e 03-dql.sql

const SEP = "-- ---------------------------------------------------------------------";

/** Quebra um comentário em linhas de até 70 caracteres, cada uma com "-- ". */
function comentar(texto, largura = 70) {
  const linhas = [];
  let atual = "";
  for (const palavra of texto.split(/\s+/u)) {
    if (atual && (atual + " " + palavra).length > largura) {
      linhas.push(`-- ${atual}`);
      atual = palavra;
    } else atual = atual ? `${atual} ${palavra}` : palavra;
  }
  if (atual) linhas.push(`-- ${atual}`);
  return linhas;
}

/** Um valor como literal do Oracle, pelo tipo da coluna. */
function literal(coluna, v) {
  if (v === null) return "NULL";
  if (coluna.tipo === "DATE") return `DATE '${v}'`;
  const numero = /^NUMBER\((\d+)(?:,(\d+))?\)$/u.exec(coluna.tipo);
  if (numero) return numero[2] ? Number(v).toFixed(Number(numero[2])) : String(v);
  return `'${String(v).replaceAll("'", "''")}'`;
}

function dml() {
  const linhas = [
    "-- =====================================================================",
    "-- OpenLabs no Telecentro — Script DML (Oracle)",
    "-- Global Solution 2026.2 · Database Design",
    "--",
    "-- Gerado por database/gerar.mjs a partir de packages/database-domain.",
    "--",
    "-- Dados de exemplo: pelo menos cinco linhas em cada tabela.",
    "-- Handbooks, fases e labs são o catálogo real do OpenLabs.",
    "-- Telecentros, monitores, alunos, computadores, progresso e notas são",
    "-- SIMULADOS: nomes fictícios e e-mails no domínio reservado example.com.",
    "-- Nenhum dado pessoal real foi usado.",
    "--",
    "-- Rodar depois de 01-ddl.sql. A ordem dos INSERTs respeita as chaves",
    "-- estrangeiras: primeiro quem é referenciado, depois quem referencia.",
    "-- =====================================================================",
  ];
  for (const t of TABELAS) {
    const dados = DADOS[t.nome];
    const colunas = t.colunas.map((c) => c.nome).join(", ");
    linhas.push("", SEP, ...comentar(`${t.nome} (${dados.linhas.length}) — ${dados.nota}`), SEP);
    for (const valores of dados.linhas) {
      linhas.push(`INSERT INTO ${t.nome} (${colunas}) VALUES (${t.colunas.map((c, i) => literal(c, valores[i] ?? null)).join(", ")});`);
    }
  }
  linhas.push("", "COMMIT;");
  return linhas.join("\n") + "\n";
}

function dql() {
  const linhas = [
    "-- =====================================================================",
    "-- OpenLabs no Telecentro — Script DQL (Oracle)",
    "-- Global Solution 2026.2 · Database Design",
    "--",
    "-- Gerado por database/gerar.mjs a partir de packages/database-domain.",
    "-- Três consultas, cada uma respondendo uma pergunta real de quem opera",
    "-- um telecentro. Rodar depois de 01-ddl.sql e 02-dml.sql.",
    "-- =====================================================================",
  ];
  for (const q of CONSULTAS) linhas.push("", SEP, `-- ${q.titulo}`, ...q.comentario.map((l) => `-- ${l}`), SEP, q.sql);
  return linhas.join("\n") + "\n";
}

// ------------------------------------------------------------------ MODELO.md

function modelo() {
  const rel = [];
  for (const t of TABELAS) for (const f of t.fks ?? []) {
    const minimo = /tem 1 ou muit/u.test(f.cardinalidade) ? "|{" : "o{";
    rel.push(`  ${f.tabela} ||--${minimo} ${t.nome} : "${semPrefixo(f.coluna)}"`);
  }
  const entidades = TABELAS.map((t) => {
    const fks = new Set((t.fks ?? []).map((f) => f.coluna));
    const cols = t.colunas.map((c) => `    ${c.tipo.replace(/\(.*$/u, "")} ${c.nome}${c.nome === t.pk ? " PK" : fks.has(c.nome) ? " FK" : c.unico ? " UK" : ""}`);
    return [`  ${t.nome} {`, ...cols, "  }"].join("\n");
  });
  return [
    "# Modelo do banco do OpenLabs no Telecentro",
    "",
    "Gerado por `database/gerar.mjs` a partir de `packages/database-domain`. É um diagrama de",
    "**conferência**: o diagrama entregue na disciplina é o do Oracle Data Modeler (veja",
    "`README.md`, seção 2). Os dois têm de mostrar as mesmas tabelas e ligações.",
    "",
    "```mermaid",
    "erDiagram",
    ...rel,
    ...entidades,
    "```",
    "",
  ].join("\n");
}

